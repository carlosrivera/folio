const UiContext = createContext({ language: 'en' as SupportedLanguage, setLanguage: (_: SupportedLanguage) => {}, tr: (text: string) => text })
const key = 'folio:interface-language'
function readLanguage(): SupportedLanguage { try { return localStorage.getItem(key) === 'es' ? 'es' : 'en' } catch { return 'en' } }
export function UiProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState(readLanguage)
  useEffect(() => {
    const update = (event: StorageEvent) => { if (event.key === key || event.key === null) setLanguage(readLanguage()) }
    window.addEventListener('storage', update)
    return () => window.removeEventListener('storage', update)
  }, [])
  useEffect(() => { document.documentElement.lang = language; try { localStorage.setItem(key, language) } catch { /* Session only. */ } }, [language])
  return <UiContext.Provider value={{ language, setLanguage, tr: text => {
    if (language !== 'es') return text
    if (spanish[text]) return spanish[text]
    const notice = text.match(/^(Opened|Saved|Exported) (.+)$/)
    return notice ? `${spanish[notice[1]] ?? notice[1]} ${notice[2]}` : text
  } }}>{children}</UiContext.Provider>
}
export const useUi = () => useContext(UiContext)
