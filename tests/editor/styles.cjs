const { app, BrowserWindow } = require('electron')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { pathToFileURL } = require('node:url')
const folder = fs.mkdtempSync(path.join(os.tmpdir(), 'folio-style-editor-'))
const sourcePath = path.join(folder, 'styles.md')
fs.writeFileSync(sourcePath, '---\ntheme: editorial\n---\n\n# Style preview\n\nA paragraph with **bold words**.\n')
fs.writeFileSync(path.join(folder, 'recent-documents.json'), JSON.stringify([sourcePath]))
app.setPath('userData', folder)
BrowserWindow.prototype.show = function () {}
const delay = ms => new Promise(resolve => setTimeout(resolve, ms))
const js = (win, code) => win.webContents.executeJavaScript(code)
async function until(win, condition, message) { for (let n = 0; n < 180; n++) { if (await js(win, condition)) return; await delay(100) } throw Error(message) }
async function click(win, selector, text) { await js(win, `Array.from(document.querySelectorAll(${JSON.stringify(selector)})).find(x => x.textContent.trim() === ${JSON.stringify(text)}).click()`); await delay(80) }
async function input(win, selector, value) { await js(win, `(() => { const input=document.querySelector(${JSON.stringify(selector)}); Object.getOwnPropertyDescriptor(Object.getPrototypeOf(input),'value').set.call(input,${JSON.stringify(value)}); input.dispatchEvent(new Event('input',{bubbles:true})); input.dispatchEvent(new Event('change',{bubbles:true})); })()`); await delay(80) }
app.whenReady().then(async () => {
  await import(pathToFileURL(path.join(__dirname, '../../dist-electron/main.js')).href)
  for (let n = 0; !BrowserWindow.getAllWindows().length && n < 60; n++) await delay(100)
  const win = BrowserWindow.getAllWindows()[0]
  try {
    await until(win, `!!document.querySelector('.cm-content') && !document.querySelector('.welcome-overlay')`, 'Editor did not open')
    await click(win, '.inspector-tab', 'Style')
    assert.equal(await js(win, `document.querySelector('.theme-editor-more').open`), false)
    await click(win, '.style-library-actions button', 'Duplicate style')
    await input(win, '.style-create-form input', 'My report')
    await click(win, '.style-create-form button', 'Create style')
    assert.equal(await js(win, `document.querySelector('.style-library-select select').selectedOptions[0].textContent`), 'My report')
    await js(win, `document.querySelector('[aria-label="Heading font"]').click()`)
    assert.ok(await js(win, `document.querySelectorAll('.font-picker-menu button small').length > 5`))
    const bounds = await js(win, `(() => { const r=document.querySelector('.font-picker-menu').getBoundingClientRect(); return {top:r.top,bottom:r.bottom,height:innerHeight}; })()`)
    assert.ok(bounds.top >= 0 && bounds.bottom <= bounds.height, JSON.stringify(bounds))
    await click(win, '.font-picker-menu button', 'Space GroteskThe quick brown fox · Aa 123')
    await until(win, `document.querySelector('.cm-content').cmTile.view.state.doc.toString().includes('Space Grotesk')`, 'Font not applied')
    await until(win, `document.querySelector('.cover-page h1') && getComputedStyle(document.querySelector('.cover-page h1')).fontFamily.includes('Space Grotesk')`, 'Preview font not applied')
    assert.equal(await js(win, `JSON.parse(localStorage.getItem('folio:styles:v1'))[0].overrides['font-display']`), undefined)
    await click(win, '.style-library-actions button', 'Save style changes')
    await click(win, '.style-library-actions button', 'Duplicate style')
    await click(win, '.style-create-form button', 'Create style')
    assert.equal(await js(win, `JSON.parse(localStorage.getItem('folio:styles:v1'))[1].overrides['font-display']`), '"Space Grotesk", Inter, sans-serif')
    await input(win, '.style-library-select select', 'voltage')
    assert.equal(await js(win, `document.querySelector('.cm-content').cmTile.view.state.doc.toString().includes('Space Grotesk')`), false)
    const id = await js(win, `JSON.parse(localStorage.getItem('folio:styles:v1'))[0].id`)
    await input(win, '.style-library-select select', id)
    assert.ok(await js(win, `document.querySelector('.cm-content').cmTile.view.state.doc.toString().includes('Space Grotesk')`))
    await click(win, '.style-library-actions button', 'New style')
    await input(win, '.style-create-form input', 'Research')
    await input(win, '.style-create-form select', 'scientific')
    await click(win, '.style-create-form button', 'Create style')
    assert.ok(await js(win, `document.querySelector('.cm-content').cmTile.view.state.doc.toString().includes('theme: scientific')`))
    assert.equal(await js(win, `document.querySelector('.cm-content').cmTile.view.state.doc.toString().includes('Space Grotesk')`), false)
    await js(win, `document.querySelector('[aria-label="Code font"]').click()`)
    assert.equal(await js(win, `document.querySelectorAll('.font-picker-menu button').length`), 3)
    await js(win, `document.activeElement.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}))`)
    assert.equal(await js(win, `!!document.querySelector('.font-picker-menu')`), false)
    assert.equal(await js(win, `document.activeElement.getAttribute('aria-label')`), 'Code font')
    await js(win, `localStorage.removeItem('folio:recovery-draft')`)
    await new Promise(resolve => { win.webContents.once('did-finish-load', resolve); win.webContents.reload() })
    await until(win, `!!document.querySelector('.cm-content') && !document.querySelector('.welcome-overlay')`, 'Editor did not reload')
    await click(win, '.inspector-tab', 'Style')
    assert.equal(await js(win, `document.querySelectorAll('.style-library-select optgroup[label="My styles"] option').length`), 3)
    await input(win, '.style-library-select select', id)
    await until(win, `!!document.querySelector('.pagination-output .pagedjs_page') && !document.querySelector('.pagination-loading')`, 'Preview did not render')
    await js(win, `document.querySelector('[aria-label="Heading font"]').click()`)
    fs.writeFileSync('/tmp/folio-style-editor.png', (await win.webContents.capturePage()).toPNG())
    console.log('Style editor passed: font previews, keyboard focus, duplicate/new styles, saved edits, switching and persistence.')
  } catch (error) { console.error(error); process.exitCode = 1 }
  finally { win.destroy(); app.exit(process.exitCode || 0) }
})
