const { app, BrowserWindow, dialog } = require('electron')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { pathToFileURL } = require('node:url')
const { unzipSync, strFromU8 } = require('fflate')
const { PDFDocument, PDFName } = require('pdf-lib')
const root = path.join(__dirname, '../..')
const folder = fs.mkdtempSync(path.join(os.tmpdir(), 'folio-writing-'))
const documentPath = path.join(folder, 'writing.md')
fs.writeFileSync(documentPath, '---\nlayout: report\nlang: en\ncustom: retained\n---\n\n# Writing\n')
fs.writeFileSync(path.join(folder, 'recent-documents.json'), JSON.stringify([documentPath]))
fs.copyFileSync(path.join(root, 'build/icon.png'), path.join(folder, 'image.png'))
app.setPath('userData', folder)
BrowserWindow.prototype.show = function () {}
const zipPath = path.join(folder, 'writing.zip'), pdfPath = path.join(folder, 'writing.pdf')
dialog.showSaveDialog = async (_win, options) => ({ canceled: false, filePath: /Package/.test(options.title) ? zipPath : /PDF/.test(options.title) ? pdfPath : documentPath })
const delay = ms => new Promise(resolve => setTimeout(resolve, ms))
const js = (win, code) => win.webContents.executeJavaScript(code)
async function until(win, expression, message) { for (let i = 0; i < 200; i++) { if (await js(win, expression)) return; await delay(100) } throw new Error(message) }
async function setDocument(win, text, position = text.length) { await js(win, `(() => { const view = document.querySelector('.cm-content').cmTile.view; view.dispatch({ changes: { from: 0, to: view.state.doc.length, insert: ${JSON.stringify(text)} }, selection: { anchor: ${position} } }); view.focus(); })()`); await delay(150) }
const text = win => js(win, `document.querySelector('.cm-content').cmTile.view.state.doc.toString()`)
async function click(win, selector, label) { await js(win, `Array.from(document.querySelectorAll(${JSON.stringify(selector)})).find(x => x.textContent.trim() === ${JSON.stringify(label)}).click()`); await delay(100) }
async function input(win, selector, value) { await js(win, `(() => { const input = document.querySelector(${JSON.stringify(selector)}); const proto = input.tagName === 'SELECT' ? HTMLSelectElement.prototype : HTMLInputElement.prototype; Object.getOwnPropertyDescriptor(proto, 'value').set.call(input, ${JSON.stringify(String(value))}); input.dispatchEvent(new Event('input', { bubbles: true })); input.dispatchEvent(new Event('change', { bubbles: true })); })()`); await delay(100) }
async function key(win, keyCode, modifiers = []) { win.webContents.sendInputEvent({ type: 'keyDown', keyCode, modifiers }); win.webContents.sendInputEvent({ type: 'keyUp', keyCode, modifiers }); await delay(150) }
app.whenReady().then(async () => {
  await import(pathToFileURL(path.join(root, 'dist-electron/main.js')).href)
  for (let i = 0; !BrowserWindow.getAllWindows().length && i < 60; i++) await delay(100)
  const win = BrowserWindow.getAllWindows()[0]
  try {
    await until(win, `!!document.querySelector('.cm-content') && !document.querySelector('.folio-new-dialog')`, 'Editor did not open')
    await setDocument(win, '- Parent\n- Child')
    await key(win, 'Tab'); assert.equal(await text(win), '- Parent\n    - Child')
    await key(win, 'Tab', ['shift']); assert.equal(await text(win), '- Parent\n- Child')
    await key(win, 'Enter'); assert.equal(await text(win), '- Parent\n- Child\n- ')
    await key(win, 'Enter'); assert.equal(await text(win), '- Parent\n- Child\n')
    await setDocument(win, '- [x] Done')
    await key(win, 'Enter'); assert.equal(await text(win), '- [x] Done\n- [ ] ')
    await key(win, 'Enter'); assert.equal(await text(win), '- [x] Done\n')
    await setDocument(win, '- [ ] Pending')
    await click(win, '.editor-toolbar button', '☑'); assert.equal(await text(win), '- [x] Pending')

    await setDocument(win, '[Original](https://example.com)', 5)
    await click(win, '.editor-toolbar button', 'Edit link')
    assert.equal(await js(win, `document.querySelectorAll('.insert-dialog input')[1].value`), 'https://example.com')
    await input(win, '.insert-dialog input', 'Updated')
    await input(win, '.insert-dialog label:nth-of-type(2) input', 'https://example.com/updated')
    await click(win, '.insert-dialog button', 'Apply')
    assert.equal(await text(win), '[Updated](<https://example.com/updated>)')

    const source = '---\nlayout: report\nlang: en\ncustom: retained\n---\n\n# Writing\n\n- [ ] Pending\n- [x] Done\n\nText with a note[^1].\n\n[^1]: Footnote evidence with **bold text**.\n\n![Image](image.png)\n\nText after image.\n\n| A | B |\n| --- | --- |\n| One | Two |\n'
    await setDocument(win, source, source.indexOf('![Image]') + 3)
    await click(win, '.editor-toolbar button', 'Edit image')
    await input(win, '.insert-dialog label:nth-of-type(4) input', 'A caption that stays below the image')
    await input(win, '.insert-dialog input[type=range]', 50)
    await click(win, '.insert-dialog button', 'Apply')
    assert.match(await text(win), /image.png> "A caption that stays below the image"\) \{width=50%\}/)
    await until(win, `document.querySelector('.pagination-stage')?.getAttribute('aria-busy') === 'false' && !!document.querySelector('.pagination-output figcaption')`, 'Image caption missing')
    const geometry = await js(win, `(() => { const figure = document.querySelector('.pagination-output .document-image'); const image = figure.querySelector('img'), caption = figure.querySelector('figcaption'); return { imageBottom: image.getBoundingClientRect().bottom, captionTop: caption.getBoundingClientRect().top, width: image.style.width, checked: document.querySelectorAll('.pagination-output .task-checkbox:checked').length, notes: document.querySelectorAll('.pagination-output .footnote-item').length }; })()`)
    assert.ok(geometry.captionTop >= geometry.imageBottom - 1)
    assert.ok(parseFloat(geometry.width) <= 79)
    assert.equal(geometry.checked, 1); assert.equal(geometry.notes, 1)

    await click(win, '.editor-toolbar button', 'Document')
    await input(win, '.document-properties [name=title]', 'Edited title')
    await input(win, '.document-properties [name=prepared-by]', 'Writer')
    await input(win, '.document-properties [name=header-left]', '{title}')
    await click(win, '.document-properties button', 'Apply')
    assert.match(await text(win), /prepared-by: Writer/); assert.match(await text(win), /custom: retained/)
    await click(win, '.editor-toolbar button', 'Document')
    assert.equal(await js(win, `Array.from(document.querySelectorAll('.document-properties button')).some(button => button.textContent.includes('page break'))`), false)
    await click(win, '.document-properties button', 'Cancel')
    await click(win, '.editor-insert-menu summary', 'Insert')
    await click(win, '.editor-insert-menu button', 'Page break')
    assert.ok((await text(win)).includes('<!-- pagebreak -->'))

    let current = await text(win)
    await js(win, `(() => { const view = document.querySelector('.cm-content').cmTile.view; view.dispatch({ selection: { anchor: ${current.indexOf('Two')} } }); view.focus(); })()`)
    await delay(100)
    await js(win, `Array.from(document.querySelectorAll('.editor-insert-menu summary')).find(x => x.textContent === 'Table').click()`)
    await until(win, `!!document.querySelector('.editor-insert-menu [popover]:popover-open')`, 'Table menu is clipped or closed')
    await click(win, '.editor-insert-menu button', 'align right')
    assert.match(await text(win), /\| --- \| ---: \|/)

    await js(win, `document.querySelector('.theme-picker-trigger').click()`)
    await until(win, `document.activeElement?.getAttribute('role') === 'menuitemradio'`, 'Theme menu did not focus an item')
    await key(win, 'Down')
    await key(win, 'Escape')
    assert.equal(await js(win, `document.activeElement === document.querySelector('.theme-picker-trigger')`), true)

    current = await text(win)
    await js(win, `document.querySelector('.export-control .save-dropdown').click()`)
    await click(win, '.export-control .save-menu button', 'Markdown + assets (.zip)')
    await until(win, `document.querySelector('.editor-status').textContent.includes('Export') === false && !!document.querySelector('.toast')`, 'Package export did not finish')
    for (let i = 0; !fs.existsSync(zipPath) && i < 50; i++) await delay(100)
    const entries = unzipSync(fs.readFileSync(zipPath))
    assert.ok(entries['writing.md']); assert.ok(Object.keys(entries).some(name => name.startsWith('assets/')))
    assert.ok(strFromU8(entries['writing.md']).includes('<assets/1-image.png>'))
    assert.equal(await text(win), current)
    const pdf = await js(win, `window.folio.exportPdf(${JSON.stringify(current)}, 'Writing', 'editorial', 'en', ${JSON.stringify(documentPath)})`)
    assert.equal(pdf.canceled, false)
    const exported = await PDFDocument.load(fs.readFileSync(pdfPath))
    assert.ok(exported.getPageCount() >= 2)
    assert.ok(exported.context.enumerateIndirectObjects().some(([, value]) => value.dict?.get(PDFName.of('Subtype')) === PDFName.of('Image')))

    await js(win, `window.folio.openSettings()`)
    let settings
    for (let i = 0; !settings && i < 50; i++) { settings = BrowserWindow.getAllWindows().find(candidate => candidate !== win && candidate.webContents.getURL().includes('mode=settings')); await delay(100) }
    await until(settings, `!!document.querySelector('.settings-window select')`, 'Settings did not open')
    assert.deepEqual(await js(settings, `Array.from(document.querySelector('.settings-window select').options).map(option => option.textContent)`), ['🇺🇸 English', '🇪🇸 Español'])
    assert.equal(await js(win, `!!document.querySelector('[title="Document language (saved in Markdown)"]')`), false)
    const contentBeforeLanguage = await text(win)
    const pagesBeforeLanguage = await js(win, `document.querySelector('.pagination-output').textContent`)
    await input(settings, '.settings-window select', 'es')
    await until(win, `document.querySelector('.save-main').textContent.includes('Guardar')`, 'Interface language did not propagate')
    assert.equal(await text(win), contentBeforeLanguage, 'Interface language rewrote document content')
    assert.equal(await js(win, `document.querySelector('.pagination-output').textContent`), pagesBeforeLanguage, 'Interface language changed document labels')
    assert.equal(await js(settings, `document.querySelector('h1').textContent`), 'Ajustes')
    await input(settings, '.settings-window select', 'en')
    settings.destroy()
    await click(win, '.toolbar-actions button', 'New')
    await until(win, `!!document.querySelector('.folio-new-dialog[open]')`, 'New document dialog did not open modally')
    await js(win, `document.querySelector('.folio-new-tabs button').focus()`)
    await key(win, 'Right')
    assert.equal(await js(win, `document.activeElement.getAttribute('aria-selected')`), 'true')
    assert.equal(await js(win, `document.activeElement.textContent.trim()`), 'Starters')
    await key(win, 'Escape')
    assert.equal(await js(win, `document.querySelector('.folio-new-dialog') === null`), true)
    assert.equal(await text(win), current)
    if (process.env.FOLIO_WRITING_SCREENSHOT) fs.writeFileSync(process.env.FOLIO_WRITING_SCREENSHOT, (await win.webContents.capturePage()).toPNG())
    console.log('Writing desktop flows passed (lists, inline editing, image captions/sizing, task lists, footnotes, properties, page breaks, alignment, keyboard menus, package/PDF export, interface language)')
  } catch (error) { console.error(error); process.exitCode = 1 }
  finally { for (const window of BrowserWindow.getAllWindows()) window.destroy(); await fs.promises.rm(folder, { recursive: true, force: true }); app.exit(process.exitCode || 0) }
})
